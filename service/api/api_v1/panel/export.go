// 导出书签
//
// 和 nav 那边的 /api/export 对齐：一份 Netscape 书签 HTML（Chrome / Edge /
// Firefox 都能直接导入），一份完整 JSON（后台看到的结构，适合备份）。
//
// 为什么走 POST 返回内容、而不是直接 GET 一个附件地址：
// 面板的鉴权走 token 请求头，浏览器地址栏直接打开带不上 token。
// 所以这里把文件内容塞进 JSON，前端自己拼 Blob 下载，token 不会进 URL。
type ExportApi struct {
}

func escHTML(s string) string {
	r := strings.NewReplacer("&", "&amp;", "<", "&lt;", ">", "&gt;", `"`, "&quot;")
	return r.Replace(s)
}

// buildBookmarksHTML 配置 → Netscape 书签 HTML
func buildBookmarksHTML(userId uint, includeHidden bool) string {
	db := global.Db
	groups := []models.ItemIconGroup{}
	_ = db.Where("user_id = ?", userId).Order("sort asc").Order("id asc").Find(&groups).Error

	now := time.Now().Unix()
	var b strings.Builder
	b.WriteString("<!DOCTYPE NETSCAPE-Bookmark-file-1>\n")
	b.WriteString("<!-- Generated by Awadaoh -->\n")
	b.WriteString("<META HTTP-EQUIV=\"Content-Type\" CONTENT=\"text/html; charset=UTF-8\">\n")
	b.WriteString("<TITLE>Bookmarks</TITLE>\n<H1>Bookmarks</H1>\n<DL><p>\n")

	for _, g := range groups {
		if g.Visible == models.GROUP_VISIBLE_HIDDEN && !includeHidden {
			continue
		}
		title := g.Title
		if strings.TrimSpace(g.Icon) != "" {
			title = g.Icon + " " + title
		}
		b.WriteString(fmt.Sprintf("    <DT><H3 ADD_DATE=\"%d\" LAST_MODIFIED=\"%d\">%s</H3>\n",
			now, now, escHTML(title)))
		b.WriteString("    <DL><p>\n")

		items := []models.ItemIcon{}
		_ = db.Where("item_icon_group_id = ? AND user_id = ?", g.ID, userId).
			Order("sort asc").Order("id asc").Find(&items).Error
		for _, it := range items {
			u := strings.TrimSpace(it.Url)
			if u == "" {
				continue
			}
			name := it.Title
			if strings.TrimSpace(name) == "" {
				name = u
			}
			attrs := fmt.Sprintf("ADD_DATE=\"%d\"", now)
			if d := strings.TrimSpace(it.Description); d != "" {
				attrs += fmt.Sprintf(" DESCRIPTION=\"%s\"", escHTML(d))
			}
			b.WriteString(fmt.Sprintf("        <DT><A HREF=\"%s\" %s>%s</A>\n",
				escHTML(u), attrs, escHTML(name)))
		}
		b.WriteString("    </DL><p>\n")
	}
	b.WriteString("</DL><p>\n")
	return b.String()
}

// buildBookmarksJSON 完整备份（不含任何口令）
func buildBookmarksJSON(userId uint) string {
	db := global.Db
	groups := []models.ItemIconGroup{}
	_ = db.Where("user_id = ?", userId).Order("sort asc").Order("id asc").Find(&groups).Error

	type site struct {
		Title       string `json:"title"`
		Url         string `json:"url"`
		LanUrl      string `json:"lanUrl"`
		Description string `json:"description"`
		Icon        string `json:"icon"`
		OpenMethod  int    `json:"openMethod"`
		Sort        int    `json:"sort"`
	}
	type group struct {
		Title       string `json:"title"`
		Icon        string `json:"icon"`
		Description string `json:"description"`
		Sort        int    `json:"sort"`
		Visible     int    `json:"visible"`
		Sites       []site `json:"sites"`
	}

	out := struct {
		App        string  `json:"app"`
		Version    int     `json:"version"`
		ExportedAt int64   `json:"exportedAt"`
		Groups     []group `json:"groups"`
	}{App: "awadaoh-panel", Version: 1, ExportedAt: time.Now().Unix(), Groups: []group{}}

	for _, g := range groups {
		gg := group{
			Title: g.Title, Icon: g.Icon, Description: g.Description,
			Sort: g.Sort, Visible: g.Visible, Sites: []site{},
		}
		items := []models.ItemIcon{}
		_ = db.Where("item_icon_group_id = ? AND user_id = ?", g.ID, userId).
			Order("sort asc").Order("id asc").Find(&items).Error
		for _, it := range items {
			gg.Sites = append(gg.Sites, site{
				Title: it.Title, Url: it.Url, LanUrl: it.LanUrl,
				Description: it.Description, Icon: it.IconJson,
				OpenMethod: it.OpenMethod, Sort: it.Sort,
			})
		}
		out.Groups = append(out.Groups, gg)
	}

	b, err := json.MarshalIndent(out, "", "  ")
	if err != nil {
		return "{}"
	}
	return string(b)
}

// Bookmarks 导出书签。format=html|json，hidden=1 时带上「前台隐藏」的分组。
func (a ExportApi) Bookmarks(c *gin.Context) {
	var req struct {
		Format        string `json:"format"`
		IncludeHidden bool   `json:"includeHidden"`
	}
	_ = c.ShouldBindJSON(&req)

	u, ok := base.GetCurrentUserInfo(c)
	if !ok {
		apiReturn.ErrorNoAccess(c)
		return
	}

	stamp := time.Now().Format("20060102-1504")
	format := strings.ToLower(strings.TrimSpace(req.Format))
	if format == "json" {
		apiReturn.SuccessData(c, gin.H{
			"filename": "awadaoh-bookmarks-" + stamp + ".json",
			"mime":     "application/json;charset=utf-8",
			"content":  buildBookmarksJSON(u.ID),
		})
		return
	}
	apiReturn.SuccessData(c, gin.H{
		"filename": "awadaoh-bookmarks-" + stamp + ".html",
		"mime":     "text/html;charset=utf-8",
		"content":  buildBookmarksHTML(u.ID, req.IncludeHidden),
	})
}
